"""Execute LLM-written verifier code in a locked-down subprocess.

verify(initial, final, trajectory, answer) -> {"passed": bool, "score": float, "evidence": str}

Safety layers:
  1. static screen: only whitelisted imports, no dunder/IO/exec names
  2. subprocess with `python -I`, CPU/memory rlimits, no cwd access, timeout
  3. output must be a small JSON object with the expected keys
The verifier is a *hidden* object — the solver never sees this code — but it is
still untrusted (generated by a model), hence the sandboxing.
"""
from __future__ import annotations

import ast
import json
import os
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

ALLOWED_IMPORTS = {"json", "math", "re", "collections", "itertools", "functools", "statistics", "datetime"}
BANNED_NAMES = {"open", "exec", "eval", "compile", "__import__", "globals", "locals", "getattr", "setattr",
                "delattr", "vars", "input", "breakpoint", "memoryview", "exit", "quit"}


@dataclass
class VerifierOutcome:
    passed: bool
    score: float
    evidence: str
    error: Optional[str] = None  # non-None => verifier itself failed (bug / timeout / unsafe)

    def to_json(self) -> Dict[str, Any]:
        return {"passed": self.passed, "score": self.score, "evidence": self.evidence, "error": self.error}


def check_verifier_code_safety(code: str) -> Tuple[bool, str]:
    try:
        tree = ast.parse(code)
    except SyntaxError as e:
        return False, f"syntax error: {e}"
    has_verify = False
    for node in ast.walk(tree):
        if isinstance(node, (ast.Import, ast.ImportFrom)):
            names = [a.name.split(".")[0] for a in node.names] if isinstance(node, ast.Import) else [
                (node.module or "").split(".")[0]]
            for n in names:
                if n not in ALLOWED_IMPORTS:
                    return False, f"import of '{n}' not allowed"
        elif isinstance(node, ast.Name) and node.id in BANNED_NAMES:
            return False, f"use of '{node.id}' not allowed"
        elif isinstance(node, ast.Attribute) and node.attr.startswith("__"):
            return False, f"dunder attribute '{node.attr}' not allowed"
        elif isinstance(node, ast.FunctionDef) and node.name == "verify":
            has_verify = True
            if len(node.args.args) != 4:
                return False, "verify must take exactly (initial, final, trajectory, answer)"
    if not has_verify:
        return False, "no verify() function"
    return True, "ok"


_RUNNER = r'''
import json, sys, resource
try:
    resource.setrlimit(resource.RLIMIT_CPU, (5, 5))
    resource.setrlimit(resource.RLIMIT_AS, (512 * 1024 * 1024, 512 * 1024 * 1024))
except Exception:
    pass
payload = json.loads(sys.stdin.read())
ns = {}
exec(compile(payload["code"], "<verifier>", "exec"), ns)
try:
    r = ns["verify"](payload["initial"], payload["final"], payload["trajectory"], payload["answer"])
except Exception as e:
    print(json.dumps({"error": f"{type(e).__name__}: {e}"}))
    sys.exit(0)
if isinstance(r, bool):
    r = {"passed": r, "score": 1.0 if r else 0.0, "evidence": ""}
elif isinstance(r, (int, float)):
    r = {"passed": r >= 1.0, "score": float(r), "evidence": ""}
elif not isinstance(r, dict):
    r = {"error": f"verify returned {type(r).__name__}"}
print(json.dumps({k: r.get(k) for k in ("passed", "score", "evidence", "error")})[:20000])
'''


def run_verifier_code(code: str, initial: Dict[str, Any], final: Dict[str, Any], trajectory: List[Dict[str, Any]],
                      answer: str, timeout_s: float = 10.0) -> VerifierOutcome:
    ok, why = check_verifier_code_safety(code)
    if not ok:
        return VerifierOutcome(False, 0.0, "", error=f"unsafe verifier: {why}")
    payload = json.dumps({"code": code, "initial": initial, "final": final, "trajectory": trajectory, "answer": answer})
    with tempfile.TemporaryDirectory() as td:
        try:
            p = subprocess.run([sys.executable, "-I", "-S", "-c", _RUNNER], input=payload, capture_output=True,
                               text=True, timeout=timeout_s, cwd=td, env={"PATH": os.environ.get("PATH", "")})
        except subprocess.TimeoutExpired:
            return VerifierOutcome(False, 0.0, "", error="verifier timeout")
    if p.returncode != 0:
        return VerifierOutcome(False, 0.0, "", error=f"verifier crashed: {p.stderr[-800:]}")
    try:
        out = json.loads(p.stdout.strip().splitlines()[-1])
    except (json.JSONDecodeError, IndexError):
        return VerifierOutcome(False, 0.0, "", error=f"verifier produced no JSON: {p.stdout[-300:]}")
    if out.get("error"):
        return VerifierOutcome(False, 0.0, "", error=str(out["error"]))
    passed = bool(out.get("passed"))
    score = out.get("score")
    score = float(score) if isinstance(score, (int, float)) else (1.0 if passed else 0.0)
    return VerifierOutcome(passed, max(0.0, min(1.0, score)), str(out.get("evidence") or "")[:2000])
